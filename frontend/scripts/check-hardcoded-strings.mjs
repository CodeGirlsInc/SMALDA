#!/usr/bin/env node

/**
 * CI script: Detect hardcoded user-facing strings in JSX/TSX files.
 * Flags text between HTML tags that isn't wrapped in a translation function.
 *
 * This is a pragmatic check — not a full AST parser. It catches obvious
 * cases like <p>Hello world</p> but allows:
 * - Strings inside t() calls
 * - className attributes
 * - data-testid attributes
 * - aria-label with t() wrapper
 * - Short technical strings (< 3 chars)
 * - Test files (fixtures are not user-facing)
 *
 * Existing violations are recorded in scripts/hardcoded-strings-baseline.json
 * so they do not block CI. Only violations that are not in the baseline fail
 * the check. Violations are keyed by file and text (not line number), so
 * unrelated edits that shift lines do not invalidate the baseline.
 *
 * Usage:
 *   node scripts/check-hardcoded-strings.mjs                    # check against baseline
 *   node scripts/check-hardcoded-strings.mjs --update-baseline  # rewrite the baseline
 */

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "fs";
import { resolve, dirname, relative, sep } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(__dirname, "..");
const baselinePath = resolve(__dirname, "hardcoded-strings-baseline.json");
const updateBaseline = process.argv.includes("--update-baseline");
const inGitHubActions = process.env.GITHUB_ACTIONS === "true";

const SKIPPED_DIRS = new Set(["node_modules", ".next", "public", "coverage", "__tests__", "test-utils", "e2e"]);

function getTsxFiles(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    const full = resolve(dir, entry);
    if (SKIPPED_DIRS.has(entry)) continue;
    if (statSync(full).isDirectory()) {
      files.push(...getTsxFiles(full));
    } else if (/\.(tsx|jsx)$/.test(entry) && !/\.(test|spec)\.(tsx|jsx)$/.test(entry)) {
      files.push(full);
    }
  }
  return files;
}

// Pattern: text content between > and < that looks like user-facing text
const HARDCODED_PATTERN = />([A-Z][a-zA-Z\s]{4,})</g;
// Ignore patterns
const IGNORE_PATTERNS = [
  /className=/,
  /data-testid=/,
  /aria-label=\{.*t\(/,
  /import /,
  /export /,
  /console\./,
  /\/\//,
  /\{\/\*/,  // JSX comments
];

function findViolations() {
  const violations = [];
  for (const file of getTsxFiles(frontendDir).sort()) {
    const relPath = relative(frontendDir, file).split(sep).join("/");
    const lines = readFileSync(file, "utf-8").split("\n");

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];

      // Skip lines that use t() or have ignore patterns
      if (IGNORE_PATTERNS.some((p) => p.test(line))) continue;
      if (line.includes("t(") || line.includes("getTranslations")) continue;

      for (const match of line.matchAll(HARDCODED_PATTERN)) {
        const text = match[1].trim();
        // Skip very short or obviously non-user-facing strings
        if (text.length < 5) continue;
        if (/^[A-Z_]+$/.test(text)) continue; // constants like "PDF", "URL"
        if (/^\d/.test(text)) continue; // starts with number

        violations.push({ file: relPath, line: i + 1, text });
      }
    }
  }
  return violations;
}

/** { [file]: { [text]: occurrences } } */
function countViolations(violations) {
  const counts = {};
  for (const { file, text } of violations) {
    counts[file] ??= {};
    counts[file][text] = (counts[file][text] ?? 0) + 1;
  }
  return counts;
}

function readBaseline() {
  if (!existsSync(baselinePath)) return {};
  return JSON.parse(readFileSync(baselinePath, "utf-8")).violations ?? {};
}

const violations = findViolations();
const current = countViolations(violations);

if (updateBaseline) {
  const total = violations.length;
  writeFileSync(
    baselinePath,
    `${JSON.stringify(
      {
        $comment:
          "Known hardcoded strings that predate the CI check. Generated by `npm run check:hardcoded -- --update-baseline`. Shrink this file as strings are translated; never add to it by hand.",
        violations: current,
      },
      null,
      2,
    )}\n`,
  );
  console.log(`✓ Baseline updated with ${total} known violation(s).`);
  process.exit(0);
}

const baseline = readBaseline();
const allowance = structuredClone(baseline);
const newViolations = [];

for (const violation of violations) {
  const remaining = allowance[violation.file]?.[violation.text] ?? 0;
  if (remaining > 0) {
    allowance[violation.file][violation.text] = remaining - 1;
  } else {
    newViolations.push(violation);
  }
}

let fixedCount = 0;
for (const texts of Object.values(allowance)) {
  for (const remaining of Object.values(texts)) fixedCount += remaining;
}

if (fixedCount > 0) {
  console.log(
    `💡 ${fixedCount} baselined string(s) are no longer hardcoded. Run \`npm run check:hardcoded -- --update-baseline\` to ratchet the baseline down.`,
  );
}

if (newViolations.length > 0) {
  for (const { file, line, text } of newViolations) {
    console.error(`⚠ ${file}:${line} — Possible hardcoded string: "${text}"`);
    if (inGitHubActions) {
      console.log(`::warning file=frontend/${file},line=${line}::Possible hardcoded string: "${text}"`);
    }
  }
  console.error(
    `\n✗ ${newViolations.length} new hardcoded string(s) found. Wrap them with a translation function (t()).`,
  );
  console.error(
    "  If a match is a false positive, rephrase the markup or add an ignore pattern to scripts/check-hardcoded-strings.mjs.",
  );
  process.exit(1);
}

console.log(
  `✓ No new hardcoded user-facing strings (${violations.length} baselined in scripts/hardcoded-strings-baseline.json).`,
);
